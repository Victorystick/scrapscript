package eval

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"

	"github.com/Victorystick/scrapscript/ast"
)

// GoConfig says what GenerateGo generates.
type GoConfig struct {
	// The name of the Go package.
	Package string
	// Whether to generate a main function too, which prints the value of
	// the scrap as `scrap eval` does.
	Main bool
}

// GenerateGo compiles the scrap s, and the scraps it refers to, to a Go
// file of native code: a package whose Eval function returns the value of
// s, and whose Print function prints it. The file embeds their sources,
// so that it needs neither a filesystem nor a network, but only rebuilds
// the program from them to print functions.
func (e *Environment) GenerateGo(s *Scrap, cfg GoConfig) ([]byte, error) {
	if cfg.Main && cfg.Package != "main" {
		return nil, fmt.Errorf("can only generate main in package main, not %s", cfg.Package)
	}
	res, err := e.infer(s)
	if err != nil {
		return nil, err
	}
	if res.Sort {
		return nil, fmt.Errorf("cannot compile a type")
	}
	c, err := compile(e.units(s), &e.reg, e.vars, e.shapes)
	if err != nil {
		return nil, err
	}

	g := &goGen{core: c, calls: make(map[cnode][]cnode)}
	// The first pass finds the functions that call each other in tail
	// position, so that the second can call the others directly.
	g.generate()
	g.cycles()
	g.analysed = true
	g.generate()

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by scrap build. DO NOT EDIT.\n\npackage %s\n\n", cfg.Package)
	out.WriteString("import (\n")
	if cfg.Main {
		out.WriteString("\t\"fmt\"\n\t\"os\"\n\n")
	}
	out.WriteString("\t\"github.com/Victorystick/scrapscript/eval\"\n\t\"github.com/Victorystick/scrapscript/label\"\n)\n\n")
	e.nativeConfig(&out, s, c)
	out.WriteString(g.decls.String())
	out.WriteString("\nfunc init() {\n")
	out.WriteString(g.inits.String())
	out.WriteString("}\n\n")
	out.WriteString(`// Eval returns the value of the scrap.
func Eval() (eval.Value, error) {
	return prog.Run(root)
}

// Print returns a scrap that evaluates to v, the value of the scrap, and
// prints the same.
func Print(v eval.Value) (string, error) {
	return prog.Print(v)
}

`)
	out.WriteString(g.funcs.String())
	if cfg.Main {
		out.WriteString(`
func main() {
	v, err := Eval()
	if err == nil {
		var s string
		if s, err = Print(v); err == nil {
			fmt.Println(s)
			return
		}
	}
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
`)
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("generated invalid Go: %w", err)
	}
	return src, nil
}

// nativeConfig writes the declaration of the NativeProgram of the core c,
// compiled from s.
func (e *Environment) nativeConfig(out *bytes.Buffer, s *Scrap, c *core) {
	out.WriteString("var prog = eval.NewNative(eval.NativeConfig{\n")
	out.WriteString("\tLabels: []string{")
	for i, name := range e.reg.Labels().Names() {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString(strconv.Quote(name))
	}
	out.WriteString("},\n\tShapes: [][]label.ID{")
	for i, s := range *e.shapes.byID.Load() {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString("{")
		for j, l := range s.labels {
			if j > 0 {
				out.WriteString(", ")
			}
			fmt.Fprint(out, l)
		}
		out.WriteString("}")
	}
	fmt.Fprintf(out, "},\n\tNodes: %d,\n", len(c.ops))
	main := c.srcs[c.main]
	static := main.rootStatic >= 0 || main.se.Kind(main.se.Expr) == ast.Where && c.whereUses(c.main, main.se.Expr) >= 0
	fmt.Fprintf(out, "\tStatic: %t,\n", static)
	fmt.Fprintf(out, "\tRoot: %s,\n", strconv.Quote(string(s.expr.Source.Bytes())))
	drafts, published := map[string]string{}, map[string]string{}
	seen := map[*Scrap]bool{}
	var visit func(s *Scrap)
	visit = func(s *Scrap) {
		for _, dep := range s.deps {
			if seen[dep] {
				continue
			}
			seen[dep] = true
			src := string(dep.expr.Source.Bytes())
			if dep.ref != "" {
				published[dep.ref[len("$source:"):]] = src
			} else {
				drafts[dep.name] = src
			}
			visit(dep)
		}
	}
	visit(s)
	writeMap := func(name string, m map[string]string) {
		if len(m) == 0 {
			return
		}
		fmt.Fprintf(out, "\t%s: map[string]string{\n", name)
		keys := make([]string, 0, len(m))
		for k := range m {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		for _, k := range keys {
			fmt.Fprintf(out, "\t\t%s: %s,\n", strconv.Quote(k), strconv.Quote(m[k]))
		}
		out.WriteString("\t},\n")
	}
	writeMap("Drafts", drafts)
	writeMap("Published", published)
	out.WriteString("})\n\n")
}

// A goGen generates the Go code of a core.
type goGen struct {
	*core
	// The declarations and initialisation of the package's variables, and
	// its functions.
	decls, inits, funcs bytes.Buffer
	// The lambdas generated so far, by node.
	fns map[cnode]*goLambda
	// The variables of builtins and constants, by their Go expression.
	vars map[string]string

	// The calls in tail position from each lambda to the lambdas it knows,
	// found by the first pass, and the cycles among them: the index of the
	// strongly connected component of each lambda that calls itself.
	analysed bool
	calls    map[cnode][]cnode
	cycle    map[cnode]int
}

// A goLambda is a lambda that is generated, or about to be.
type goLambda struct {
	node cnode
	// The lambda that each capture is known to be, or none.
	caps []cnode
	done bool
}

// A goFunc is a Go function being generated: a lambda, or the root.
type goFunc struct {
	g     *goGen
	node  cnode // the lambda, or none for the root
	arity int
	b     bytes.Buffer
	depth int
	temps int
	// The lambda that a slot or capture is known to hold, or none.
	known []cnode
	caps  []cnode
	// Whether it calls itself in tail position, and loops.
	loops bool
}

// generate generates the root and the lambdas it makes.
func (g *goGen) generate() {
	g.vars = make(map[string]string)
	g.fns = make(map[cnode]*goLambda)
	g.decls.Reset()
	g.inits.Reset()
	g.funcs.Reset()
	f := &goFunc{g: g, node: none, known: make([]cnode, g.top)}
	f.depth = 1
	f.tail(g.root)
	g.emit("root", "t *eval.Tail", f)
	// Lambdas are queued as their closures are made.
	for {
		var todo []*goLambda
		for _, l := range g.fns {
			if !l.done {
				todo = append(todo, l)
			}
		}
		if len(todo) == 0 {
			break
		}
		slices.SortFunc(todo, func(a, b *goLambda) int { return int(a.node - b.node) })
		for _, l := range todo {
			l.done = true
			g.lambda(l)
		}
	}
}

// emit writes the function f with its body.
func (g *goGen) emit(name, params string, f *goFunc) {
	fmt.Fprintf(&g.funcs, "func %s(%s) eval.Value {\n", name, params)
	if n := len(f.known); n > 0 {
		var slots []string
		for i := range n {
			slots = append(slots, fmt.Sprintf("s%d", i))
		}
		fmt.Fprintf(&g.funcs, "\tvar %s eval.Value\n", strings.Join(slots, ", "))
		fmt.Fprintf(&g.funcs, "\t%s = %s\n", strings.Repeat("_, ", n-1)+"_", strings.Join(slots, ", "))
	}
	if f.loops {
		g.funcs.WriteString("top:\n")
	}
	g.funcs.Write(f.b.Bytes())
	g.funcs.WriteString("}\n\n")
}

// lambda generates the function of the lambda l.
func (g *goGen) lambda(l *goLambda) {
	n := l.node
	size, _, arity, arms := g.core.lambda(n)
	f := &goFunc{g: g, node: n, arity: arity, known: make([]cnode, size), caps: l.caps}
	f.depth = 1
	var params []string
	for i := range arity {
		params = append(params, fmt.Sprintf("a%d", i))
	}
	if arity > 1 {
		var slots []string
		for i := range arity {
			slots = append(slots, fmt.Sprintf("s%d", i))
		}
		f.line("%s = %s", strings.Join(slots, ", "), strings.Join(params, ", "))
	}
	f.arms(len(arms)/(arity+1), func(i int) string {
		conds := make([]string, arity)
		for j, p := range arms[i*(arity+1) : i*(arity+1)+arity] {
			x := fmt.Sprintf("s%d", j)
			if arity == 1 {
				x = "a0"
			}
			conds[j] = f.pattern(cnode(p), x)
		}
		return and(conds...)
	}, func(i int) { f.tail(cnode(arms[i*(arity+1)+arity])) })
	name := fmt.Sprintf("f%d", n)
	g.emit(name, "t *eval.Tail, c []eval.Value, "+strings.Join(params, ", ")+" eval.Value", f)

	code := fmt.Sprintf("code%d", n)
	fmt.Fprintf(&g.decls, "var %s = eval.NativeCode{Node: %d, Arity: %d}\n", code, n, arity)
	switch arity {
	case 1, 2, 3:
		fmt.Fprintf(&g.inits, "\t%s.F%d = %s\n", code, arity, name)
	default:
		args := make([]string, arity)
		for i := range args {
			args[i] = fmt.Sprintf("a[%d]", i)
		}
		fmt.Fprintf(&g.inits, "\t%s.FN = func(t *eval.Tail, c []eval.Value, a []eval.Value) eval.Value { return %s(t, c, %s) }\n",
			code, name, strings.Join(args, ", "))
	}
}

func and(conds ...string) string {
	var cs []string
	for _, c := range conds {
		if c != "true" {
			cs = append(cs, c)
		}
	}
	if len(cs) == 0 {
		return "true"
	}
	return strings.Join(cs, " && ")
}

func (f *goFunc) line(format string, args ...any) {
	f.b.WriteString(strings.Repeat("\t", f.depth))
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}

// temp returns a new temporary variable.
func (f *goFunc) temp() string {
	f.temps++
	return fmt.Sprintf("v%d", f.temps)
}

// let binds x to a temporary, unless it is a variable already.
func (f *goFunc) let(x string) string {
	if isVar(x) {
		return x
	}
	v := f.temp()
	f.line("%s := %s", v, x)
	return v
}

func isVar(x string) bool {
	for i, r := range x {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9' && i > 0:
		case r == '[' || r == ']':
		default:
			return false
		}
	}
	return true
}

// global returns a package variable initialised to x.
func (g *goGen) global(prefix, x string) string {
	if v, ok := g.vars[x]; ok {
		return v
	}
	v := fmt.Sprintf("%s%d", prefix, len(g.vars))
	g.vars[x] = v
	fmt.Fprintf(&g.decls, "var %s = %s\n", v, x)
	return v
}

// konst returns the Go expression of the constant i.
func (g *goGen) konst(i int32) string {
	v := g.consts[i]
	switch v.kind() {
	case kindHole:
		return "eval.NHole()"
	case kindInt:
		return fmt.Sprintf("eval.NInt(%d)", v.asInt())
	case kindFloat:
		return fmt.Sprintf("eval.NFloat(%s)", strconv.FormatFloat(v.asFloat(), 'g', -1, 64))
	case kindByte:
		return fmt.Sprintf("eval.NByte(%#02x)", v.asByte())
	case kindText:
		return fmt.Sprintf("eval.NText(%s)", strconv.Quote(v.asText()))
	case kindBytes:
		return g.global("k", fmt.Sprintf("eval.NBytes([]byte(%s))", strconv.Quote(string(v.asBytes()))))
	case kindBuiltin:
		return g.global("b", fmt.Sprintf("prog.Builtin(%s)", strconv.Quote(v.asBuiltin().name)))
	}
	panic(fmt.Sprintf("eval: constant of kind %s", v.kind()))
}

// expr returns the Go expression of n, writing the statements that compute
// it first. A call or match is in a temporary, so that the statements
// compute values in order.
func (f *goFunc) expr(n cnode) string {
	g := f.g
	d := g.data[n]
	switch g.ops[n] {
	case opConst:
		return g.konst(d.a)
	case opLocal:
		return fmt.Sprintf("s%d", d.a)
	case opCapture:
		return fmt.Sprintf("c[%d]", d.a)
	case opCall, opCallN:
		return f.call(n, false)

	case opAddInt:
		return f.binary(n, "eval.NInt(eval.NAsInt(%s) + eval.NAsInt(%s))")
	case opSubInt:
		return f.binary(n, "eval.NInt(eval.NAsInt(%s) - eval.NAsInt(%s))")
	case opMulInt:
		return f.binary(n, "eval.NInt(eval.NAsInt(%s) * eval.NAsInt(%s))")
	case opAddFloat:
		return f.binary(n, "eval.NFloat(eval.NAsFloat(%s) + eval.NAsFloat(%s))")
	case opSubFloat:
		return f.binary(n, "eval.NFloat(eval.NAsFloat(%s) - eval.NAsFloat(%s))")
	case opMulFloat:
		return f.binary(n, "eval.NFloat(eval.NAsFloat(%s) * eval.NAsFloat(%s))")
	case opAppendList:
		return f.binary(n, "eval.NAppendList(%s, %s)")
	case opAppendBytes:
		return f.binary(n, "eval.NAppendBytes(%s, %s)")
	case opPrependList:
		return f.binary(n, "eval.NPrependList(%s, %s)")
	case opPrependBytes:
		return f.binary(n, "eval.NPrependBytes(%s, %s)")
	case opConcatList:
		return f.binary(n, "eval.NConcatList(%s, %s)")
	case opConcatText:
		return f.binary(n, "eval.NConcatText(%s, %s)")
	case opConcatBytes:
		return f.binary(n, "eval.NConcatBytes(%s, %s)")

	case opMatch, opMatchN, opWhere:
		v := f.temp()
		f.line("var %s eval.Value", v)
		f.control(n, func(body cnode) { f.line("%s = %s", v, f.expr(body)) })
		return v

	case opCompose:
		first, second, _ := g.compose(n)
		code := g.global("compose", fmt.Sprintf("eval.NComposeCode(%d)", n))
		a := f.expr(first)
		b := f.expr(second)
		return f.let(fmt.Sprintf("eval.NClosure(%s, %s, %s)", code, a, b))

	case opLambda:
		caps := f.captures(n)
		if len(caps) == 0 {
			v := fmt.Sprintf("fn%d", n)
			if _, ok := g.vars[v]; !ok {
				g.vars[v] = v
				fmt.Fprintf(&g.decls, "var %s eval.Value\n", v)
				fmt.Fprintf(&g.inits, "\t%s = eval.NClosure(&code%d)\n", v, n)
			}
			return v
		}
		return f.let(fmt.Sprintf("eval.NClosure(&code%d, %s)", n, strings.Join(caps, ", ")))

	case opFill:
		caps := f.captures(cnode(d.a))
		f.line("eval.NFill(s%d, %s)", d.b, strings.Join(caps, ", "))
		return fmt.Sprintf("s%d", d.b)

	case opRecord:
		base, s, fields := g.record(n)
		vals := make([]string, len(fields)/2)
		for i := range vals {
			vals[i] = f.expr(cnode(fields[2*i+1]))
		}
		if base == none {
			ordered := make([]string, len(vals))
			for i, v := range vals {
				ordered[fields[2*i]] = v
			}
			return f.let(fmt.Sprintf("eval.NRecord(%d, %s)", s.id, strings.Join(ordered, ", ")))
		}
		b := f.let(f.expr(base))
		r := f.temp()
		f.line("%s := eval.NCopyFields(%s)", r, b)
		for i, v := range vals {
			if s != nil {
				f.line("%s[%d] = %s", r, fields[2*i], v)
			} else {
				f.line("%s[prog.NIndex(%s, %d)] = %s", r, b, fields[2*i], v)
			}
		}
		return f.let(fmt.Sprintf("eval.NRecordLike(%s, %s)", b, r))

	case opAccess:
		return fmt.Sprintf("prog.NGet(%s, %d)", f.expr(cnode(d.a)), d.b)
	case opField:
		return fmt.Sprintf("eval.NField(%s, %d)", f.expr(cnode(d.a)), d.b)

	case opList:
		elems := g.range_(n)
		vals := make([]string, len(elems))
		for i, x := range elems {
			vals[i] = f.expr(cnode(x))
		}
		return f.let(fmt.Sprintf("eval.NList(%s)", strings.Join(vals, ", ")))

	case opVariant:
		if cnode(d.b) == none {
			return fmt.Sprintf("eval.NTag(%d)", d.a)
		}
		return f.let(fmt.Sprintf("eval.NVariant(%d, %s)", d.a, f.expr(cnode(d.b))))
	}
	panic(fmt.Sprintf("eval: unhandled op %d", g.ops[n]))
}

// binary returns the operator n, whose Go expression is format of its
// operands.
func (f *goFunc) binary(n cnode, format string) string {
	d := f.g.data[n]
	a := f.let(f.expr(cnode(d.a)))
	b := f.let(f.expr(cnode(d.b)))
	return fmt.Sprintf(format, a, b)
}

// tail writes the statements that return the value of n, in tail
// position.
func (f *goFunc) tail(n cnode) {
	switch f.g.ops[n] {
	case opCall, opCallN:
		f.call(n, true)
	case opMatch, opMatchN, opWhere:
		f.control(n, f.tail)
	default:
		f.line("return %s", f.expr(n))
	}
}

// control writes a match or where-group n, with body writing each body in
// it.
func (f *goFunc) control(n cnode, body func(cnode)) {
	g := f.g
	switch g.ops[n] {
	case opMatch:
		r := g.range_(n)
		v := f.let(f.expr(cnode(r[0])))
		if !strings.HasPrefix(v, "s") {
			f.line("_ = %s", v) // in case no pattern reads it
		}
		arms := r[1:]
		f.arms(len(arms)/2, func(i int) string { return f.pattern(cnode(arms[2*i]), v) },
			func(i int) { body(cnode(arms[2*i+1])) })

	case opMatchN:
		r := g.range_(n)
		s, k := r[0], int(r[1])
		args := r[2 : 2+k]
		vals := make([]string, k)
		slots := make([]string, k)
		for i, x := range args {
			vals[i] = f.expr(cnode(x))
			slots[i] = fmt.Sprintf("s%d", int(s)+i)
			f.known[int(s)+i] = none
		}
		f.line("%s = %s", strings.Join(slots, ", "), strings.Join(vals, ", "))
		arms := r[2+k:]
		f.arms(len(arms)/(k+1), func(i int) string {
			conds := make([]string, k)
			for j, p := range arms[i*(k+1) : i*(k+1)+k] {
				conds[j] = f.pattern(cnode(p), slots[j])
			}
			return and(conds...)
		}, func(i int) { body(cnode(arms[i*(k+1)+k])) })

	case opWhere:
		b, binds := g.where(n)
		saved := slices.Clone(f.known)
		for i := 0; i < len(binds); i += 2 {
			s, x := binds[i], cnode(binds[i+1])
			if s < 0 {
				f.known[-1-s] = x
				f.line("s%d = eval.NRec(&code%d, %d)", -1-s, x, len(g.captures(x)))
				continue
			}
			v := f.expr(x)
			if g.ops[x] == opLambda {
				f.known[s] = x
			}
			if v != fmt.Sprintf("s%d", s) {
				f.line("s%d = %s", s, v)
			}
		}
		body(b)
		copy(f.known, saved)
	}
}

// arms writes n arms, of which cond returns the condition of each and body
// writes its body. In tail position, each body returns; otherwise, the
// arms are an if-else chain.
func (f *goFunc) arms(n int, cond func(int) string, body func(int)) {
	for i := range n {
		c := cond(i)
		switch {
		case c == "true" && i == 0:
			f.line("{")
		case c == "true":
			f.line("} else {")
		case i == 0:
			f.line("if %s {", c)
		default:
			f.line("} else if %s {", c)
		}
		f.depth++
		body(i)
		f.depth--
		if c == "true" {
			f.line("}")
			return
		}
	}
	f.line("} else {")
	f.line("\tpanic(eval.NNoArm())")
	f.line("}")
}

// captures returns the Go expressions of what the lambda n captures, and
// queues it to be generated with what they are known to be.
func (f *goFunc) captures(n cnode) []string {
	from := f.g.captures(n)
	caps := make([]string, len(from))
	known := make([]cnode, len(from))
	for i, x := range from {
		if x >= 0 {
			caps[i] = fmt.Sprintf("s%d", x)
			known[i] = f.known[x]
		} else {
			caps[i] = fmt.Sprintf("c[%d]", -1-x)
			known[i] = f.caps[-1-x]
		}
	}
	if _, ok := f.g.fns[n]; !ok {
		f.g.fns[n] = &goLambda{node: n, caps: known}
	}
	return caps
}

// knownLambda returns the lambda that the expression n holds, if known.
func (f *goFunc) knownLambda(n cnode) cnode {
	d := f.g.data[n]
	switch f.g.ops[n] {
	case opLocal:
		return f.known[d.a]
	case opCapture:
		return f.caps[d.a]
	}
	return none
}

// call writes the call n, returning its value, or in tail position
// returning from the function with it.
func (f *goFunc) call(n cnode, tail bool) string {
	g := f.g
	d := g.data[n]
	var fn cnode
	var argNodes []int32
	if g.ops[n] == opCall {
		fn, argNodes = cnode(d.a), []int32{d.b}
	} else {
		r := g.range_(n)
		fn, argNodes = cnode(r[0]), r[1:]
	}
	k := len(argNodes)
	result := func(x string) string {
		if tail {
			f.line("return %s", x)
			return ""
		}
		v := f.temp()
		f.line("%s := %s", v, x)
		return v
	}

	// A builtin of that many arguments.
	if bf, ok := g.builtin(fn); ok && bf.arity == k && k <= 3 {
		args := f.args(argNodes)
		v := g.global("bf", fmt.Sprintf("eval.NBuiltin%d(%s)", k, g.konst(g.data[fn].a)))
		return result(fmt.Sprintf("%s(%s)", v, strings.Join(args, ", ")))
	}

	// A lambda of that many arguments, which is known.
	if l := f.knownLambda(fn); l != none {
		if _, _, arity, _ := g.core.lambda(l); arity == k {
			fv := f.expr(fn)
			args := f.args(argNodes)
			caps := "nil"
			if len(g.captures(l)) > 0 {
				caps = fmt.Sprintf("eval.NCaps(%s)", fv)
			}
			switch {
			case tail && l == f.node:
				params := make([]string, k)
				for i := range params {
					params[i] = fmt.Sprintf("a%d", i)
				}
				f.line("%s = %s", strings.Join(params, ", "), strings.Join(args, ", "))
				f.line("goto top")
				f.loops = true
				return ""
			case tail && f.node != none && !g.analysed:
				g.calls[f.node] = append(g.calls[f.node], l)
			case tail && f.node != none && g.cycle[f.node] == g.cycle[l] && g.cycle[l] != 0:
				return result(fmt.Sprintf("t.Pend(&code%d, %s, %s)", l, caps, strings.Join(args, ", ")))
			case !tail:
				return result(fmt.Sprintf("t.Settle(f%d(t, %s, %s))", l, caps, strings.Join(args, ", ")))
			}
			return result(fmt.Sprintf("f%d(t, %s, %s)", l, caps, strings.Join(args, ", ")))
		}
	}

	fv := f.expr(fn)
	args := f.args(argNodes)
	name := "Call"
	if tail {
		name = "Tail"
	}
	switch k {
	case 1, 2:
		name += strconv.Itoa(k)
	default:
		name += "N"
	}
	return result(fmt.Sprintf("eval.N%s(t, %s, %s)", name, fv, strings.Join(args, ", ")))
}

// args returns the Go expressions of the arguments ns, in order.
func (f *goFunc) args(ns []int32) []string {
	args := make([]string, len(ns))
	for i, x := range ns {
		args[i] = f.let(f.expr(cnode(x)))
	}
	return args
}

// pattern returns the condition that x matches the pattern n, which binds
// the slots it names as it goes.
func (f *goFunc) pattern(n cnode, x string) string {
	g := f.g
	d := g.data[n]
	switch g.ops[n] {
	case patBind:
		f.known[d.a] = none
		return fmt.Sprintf("eval.NBind(&s%d, %s)", d.a, x)
	case patArg, patWild:
		return "true"
	case patLiteral:
		c := g.consts[d.a]
		switch c.kind() {
		case kindText:
			return fmt.Sprintf("eval.NAsText(%s) == %s", x, strconv.Quote(c.asText()))
		case kindBytes:
			return fmt.Sprintf("eval.NBytesEqual(%s, %s)", x, strconv.Quote(string(c.asBytes())))
		case kindHole:
			return "true"
		}
		return fmt.Sprintf("eval.NWord(%s) == %#x", x, c.n)
	case patVariant:
		cond := fmt.Sprintf("eval.NHasTag(%s, %d)", x, d.a)
		if cnode(d.b) == none {
			return cond
		}
		return and(cond, f.pattern(cnode(d.b), fmt.Sprintf("eval.NPayload(%s)", x)))
	case patRecord:
		rest, s, fields := g.record(n)
		conds := make([]string, 0, len(fields)/2+1)
		for i := 0; i < len(fields); i += 2 {
			key, p := fields[i], cnode(fields[i+1])
			if rest == none {
				conds = append(conds, f.pattern(p, fmt.Sprintf("eval.NField(%s, %d)", x, key)))
			} else {
				conds = append(conds, f.pattern(p, fmt.Sprintf("prog.NGet(%s, %d)", x, s.labels[key])))
			}
		}
		if rest != none {
			conds = append(conds, f.pattern(rest, fmt.Sprintf("prog.NWithout(%s, %d)", x, s.id)))
		}
		return and(conds...)
	case patSplit:
		rest, _, rs, from, fields := g.split(n)
		conds := make([]string, 0, len(fields)/2+1)
		for i := 0; i < len(fields); i += 2 {
			conds = append(conds, f.pattern(cnode(fields[i+1]), fmt.Sprintf("eval.NField(%s, %d)", x, fields[i])))
		}
		idx := make([]string, len(from))
		for i, j := range from {
			idx[i] = strconv.Itoa(int(j))
		}
		pick := fmt.Sprintf("eval.NPick(%s, %d", x, rs.id)
		if len(idx) > 0 {
			pick += ", " + strings.Join(idx, ", ")
		}
		conds = append(conds, f.pattern(rest, pick+")"))
		return and(conds...)
	case patList:
		elems := g.range_(n)
		conds := []string{fmt.Sprintf("eval.NLen(%s) == %d", x, len(elems))}
		for i, p := range elems {
			conds = append(conds, f.pattern(cnode(p), fmt.Sprintf("eval.NElem(%s, %d)", x, i)))
		}
		return and(conds...)
	case patCons:
		return and(fmt.Sprintf("eval.NLen(%s) > 0", x),
			f.pattern(cnode(d.a), fmt.Sprintf("eval.NElem(%s, 0)", x)),
			f.pattern(cnode(d.b), fmt.Sprintf("eval.NSlice(%s, 1, eval.NLen(%s))", x, x)))
	case patSnoc:
		return and(fmt.Sprintf("eval.NLen(%s) > 0", x),
			f.pattern(cnode(d.a), fmt.Sprintf("eval.NSlice(%s, 0, eval.NLen(%s)-1)", x, x)),
			f.pattern(cnode(d.b), fmt.Sprintf("eval.NElem(%s, eval.NLen(%s)-1)", x, x)))
	case patPrefix:
		rest, elems := g.elems(n)
		k := len(elems)
		conds := []string{fmt.Sprintf("eval.NLen(%s) >= %d", x, k)}
		for i, p := range elems {
			conds = append(conds, f.pattern(cnode(p), fmt.Sprintf("eval.NElem(%s, %d)", x, i)))
		}
		conds = append(conds, f.pattern(rest, fmt.Sprintf("eval.NSlice(%s, %d, eval.NLen(%s))", x, k, x)))
		return and(conds...)
	case patSuffix:
		rest, elems := g.elems(n)
		k := len(elems)
		conds := []string{fmt.Sprintf("eval.NLen(%s) >= %d", x, k)}
		conds = append(conds, f.pattern(rest, fmt.Sprintf("eval.NSlice(%s, 0, eval.NLen(%s)-%d)", x, x, k)))
		for i, p := range elems {
			conds = append(conds, f.pattern(cnode(p), fmt.Sprintf("eval.NElem(%s, eval.NLen(%s)-%d)", x, x, k-i)))
		}
		return and(conds...)
	}
	panic(fmt.Sprintf("eval: unhandled pattern %d", g.ops[n]))
}

// cycles finds the lambdas that call each other in tail position, as the
// strongly connected components of the calls (Tarjan 1972), numbered from
// 1. A lambda in none is not in g.cycle.
func (g *goGen) cycles() {
	index := map[cnode]int{}
	low := map[cnode]int{}
	on := map[cnode]bool{}
	var stack []cnode
	next, comp := 0, 0
	g.cycle = map[cnode]int{}
	var visit func(v cnode)
	visit = func(v cnode) {
		index[v], low[v] = next, next
		next++
		stack = append(stack, v)
		on[v] = true
		for _, w := range g.calls[v] {
			if _, ok := index[w]; !ok {
				visit(w)
				low[v] = min(low[v], low[w])
			} else if on[w] {
				low[v] = min(low[v], index[w])
			}
		}
		if low[v] != index[v] {
			return
		}
		comp++
		var members []cnode
		for {
			w := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			on[w] = false
			members = append(members, w)
			if w == v {
				break
			}
		}
		if len(members) > 1 {
			for _, w := range members {
				g.cycle[w] = comp
			}
		}
	}
	nodes := make([]cnode, 0, len(g.calls))
	for v := range g.calls {
		nodes = append(nodes, v)
	}
	slices.Sort(nodes)
	for _, v := range nodes {
		if _, ok := index[v]; !ok {
			visit(v)
		}
	}
}
